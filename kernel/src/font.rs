/// The bitmap for `ch`, or `None` when the table does not cover it.
pub fn glyph(ch: char) -> Option<&'static [u8; GLYPH_HEIGHT]> {
    let index = (ch as usize).checked_sub(FIRST as usize)?;
    GLYPHS.get(index)
}

/// The bitmap for `ch`, or [`FALLBACK`] for anything the table does not cover.
pub fn glyph_or_fallback(ch: char) -> &'static [u8; GLYPH_HEIGHT] {
    glyph(ch).unwrap_or(&FALLBACK)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn covers_every_printable_ascii_character() {
        for code in 0x20u8..=0x7e {
            let ch = char::from(code);
            assert!(glyph(ch).is_some(), "{ch:?} should have a glyph");
        }
    }

    #[test]
    fn refuses_control_characters_and_non_ascii() {
        for ch in ['\0', '\n', '\r', '\t', '\u{7f}', 'é', '€'] {
            assert!(glyph(ch).is_none(), "{ch:?} should not have a glyph");
        }
    }

    #[test]
    fn falls_back_to_a_visible_box() {
        assert_eq!(glyph_or_fallback('\n'), &FALLBACK);
        assert_eq!(glyph_or_fallback('A'), glyph('A').unwrap());
    }

    #[test]
    fn space_is_blank_and_visible_characters_have_ink() {
        assert_eq!(glyph(' '), Some(&[0u8; GLYPH_HEIGHT]));
        for ch in ['A', 'a', '0', '#', '~'] {
            let rows = glyph(ch).expect("printable ASCII is covered");
            assert!(
                rows.iter().any(|row| *row != 0),
                "{ch:?} should draw at least one pixel"
            );
        }
    }

    #[test]
    fn keeps_the_source_bitmap_for_the_letter_a() {
        // Copied from the upstream table. A transposed row or a flipped bit order is
        // caught here rather than by squinting at the panel.
        assert_eq!(
            glyph('A'),
            Some(&[0x0c, 0x1e, 0x33, 0x33, 0x3f, 0x33, 0x33, 0x00])
        );
    }
}
