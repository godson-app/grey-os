//! The console's typeface: one 8x8 bitmap per printable ASCII character.
//!
//! Embedded data rather than a font crate: the kernel needs a legible boot log before it
//! can run anything that would help debug a dependency, and this table is small enough
//! to read. Every glyph is eight bytes, one per row, with **bit 0 of each byte the
//! leftmost pixel** - the convention the source uses, kept as-is so the table can be
//! diffed against it. The classic `A` (`0c 1e 33 33 3f 33 33 00`) is what proves the
//! convention was read the right way round.
//!
//! Provenance (ADR-024):
//!
//! * `font8x8_basic.h`, "8x8 monochrome bitmap fonts for rendering", by Daniel Hepper,
//!   public domain, itself based on Marcel Sondaar's public-domain IBM VGA fonts:
//!   <https://github.com/dhepper/font8x8/blob/master/font8x8_basic.h>
//! * Fetched 2026-10-26, sha256
//!   `49d8df366296b203ca3211bc0672cf2a762135bf12710735b6292756b19dffd5`.
//! * Only 0x20-0x7e are embedded: the console handles control characters itself, and a
//!   character outside ASCII is a decision for the day a Unicode-capable font lands.
//!
//! The data is 8x8, which is small on a 1280x800 panel, so `text.rs` draws it at an
//! integer scale. Keeping it at its native size means a better face later is a swap of
//! this file rather than a rewrite of the renderer.

/// Width of one glyph in pixels, before any scale factor.
pub const GLYPH_WIDTH: usize = 8;

/// Height of one glyph in pixels, before any scale factor.
pub const GLYPH_HEIGHT: usize = 8;

/// First character the table covers, the start of printable ASCII.
pub const FIRST: char = ' ';

/// Last character the table covers.
pub const LAST: char = '~';

/// Drawn for a character the table does not cover, so an unexpected byte shows up as a
